// Turns data/seed.json into supabase/seed.sql  →  node scripts/build-seed.mjs
// Add a country? Append it to seed.json, re-run, then `supabase db reset` or paste seed.sql in the SQL editor.
import fs from 'node:fs';
const d = JSON.parse(fs.readFileSync(new URL('../data/seed.json', import.meta.url)));
const q = v => v === null || v === undefined ? 'null'
  : typeof v === 'number' || typeof v === 'boolean' ? String(v)
  : typeof v === 'object' ? `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`
  : `'${String(v).replace(/'/g, "''")}'`;
let s = '-- Generated by scripts/build-seed.mjs — edit data/seed.json, not this file.\n\n';
for (const c of d.countries) {
  s += `insert into public.countries (iso_a3,name,region,tagline,palette,active,sort_order) values (${[c.iso_a3,c.name,c.region,c.tagline,c.palette,c.active,c.sort_order].map(q).join(',')})\n  on conflict (iso_a3) do update set name=excluded.name, region=excluded.region, tagline=excluded.tagline, palette=excluded.palette, active=excluded.active, sort_order=excluded.sort_order;\n`;
}
s += '\n';
const cols = ['slug','country_iso','name','local_name','category','lat','lng','summary','uniqueness','stat_label','stat_value','unesco','visible','sort_order','art'];
for (const w of d.wonders) {
  s += `insert into public.wonders (${cols.join(',')}) values (${cols.map(k => q(w[k])).join(',')})\n  on conflict (slug) do update set ${cols.filter(k=>k!=='slug').map(k=>`${k}=excluded.${k}`).join(', ')};\n`;
}
s += `\ninsert into public.presentation (id, settings) values ('default', ${q(d.presentation)})\n  on conflict (id) do update set settings = excluded.settings;\n`;
fs.writeFileSync(new URL('../supabase/seed.sql', import.meta.url), s);
console.log(`seed.sql: ${d.countries.length} countries, ${d.wonders.length} wonders`);
